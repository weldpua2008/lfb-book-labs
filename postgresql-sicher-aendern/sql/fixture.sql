DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;
COMMENT ON SCHEMA shop IS 'lfb_pg_book_20261118';
CREATE TABLE shop.schema_versions(version integer PRIMARY KEY, description text NOT NULL);
INSERT INTO shop.schema_versions VALUES(1,'Deterministischer Ausgangsbestand');
CREATE TABLE shop.customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_no text NOT NULL UNIQUE,
  display_name text NOT NULL,
  email text NOT NULL UNIQUE CHECK (email LIKE '%@example.invalid'),
  region text NOT NULL CHECK(region IN ('Nord','Süd','Ost','West'))
);
CREATE TABLE shop.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL UNIQUE,
  name text NOT NULL,
  unit_price_cents integer NOT NULL CHECK(unit_price_cents>0),
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE shop.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES shop.customers(id),
  order_no text NOT NULL UNIQUE,
  placed_at timestamptz NOT NULL,
  status text NOT NULL CHECK(status IN ('bezahlt','offen','storniert')),
  total_cents bigint NOT NULL DEFAULT 0 CHECK(total_cents>=0),
  idempotency_key text NOT NULL UNIQUE,
  updated_at timestamptz NOT NULL DEFAULT '2026-01-01T00:00:00Z'
);
CREATE TABLE shop.order_items (
  order_id bigint NOT NULL REFERENCES shop.orders(id) ON DELETE CASCADE,
  line_no smallint NOT NULL CHECK(line_no>0),
  product_id bigint NOT NULL REFERENCES shop.products(id),
  quantity smallint NOT NULL CHECK(quantity BETWEEN 1 AND 100),
  unit_price_cents integer NOT NULL CHECK(unit_price_cents>0),
  PRIMARY KEY(order_id,line_no)
);
CREATE INDEX order_items_product_idx ON shop.order_items(product_id);
CREATE TABLE shop.payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL UNIQUE REFERENCES shop.orders(id),
  amount_cents bigint NOT NULL CHECK(amount_cents>0),
  provider_reference text NOT NULL UNIQUE,
  paid_at timestamptz NOT NULL
);
CREATE TABLE shop.inventory (
  product_id bigint PRIMARY KEY REFERENCES shop.products(id),
  available integer NOT NULL CHECK(available>=0),
  reserved integer NOT NULL DEFAULT 0 CHECK(reserved>=0)
);
CREATE TABLE shop.migration_checkpoints (
  migration_id text PRIMARY KEY,
  last_id bigint NOT NULL DEFAULT 0,
  finished boolean NOT NULL DEFAULT false
);
